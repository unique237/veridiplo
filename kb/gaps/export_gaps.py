#!/usr/bin/env python3
"""Merge the seed gap register (seed_gaps.yaml) with runtime gaps (GapAnalystAgent) -> gap_register.json + gap_register.md.

    python kb/gaps/export_gaps.py                         # seed only
    python kb/gaps/export_gaps.py --runtime gaps.json     # + runtime gaps from a JSON file (list or {"gaps": [...]})
    python kb/gaps/export_gaps.py --db                    # + runtime gaps from Postgres (table `gaps`, app.core.models.GapRecord)

Anchors in `law_cited` are resolved against kb/chunks/anchors.json; unresolved anchors are listed (never silently dropped).
Output is deterministic (no timestamps) so the export is idempotent.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
KB = Path(os.environ.get("KB_DIR") or HERE.parent).resolve()


def load_chunks() -> dict:
    out = {}
    for p in sorted((KB / "chunks").glob("*.jsonl")):
        for line in open(p, encoding="utf-8"):
            if line.strip():
                c = json.loads(line)
                out[c["chunk_id"]] = c
    return out


def runtime_from_db() -> list[dict]:
    sys.path.insert(0, str(KB.parent))
    from app.core.db import session_scope
    from app.core.models import GapRecord

    out = []
    with session_scope() as s:
        for g in s.query(GapRecord).order_by(GapRecord.id).all():
            d = dict(g.detail or {})
            out.append({"id": g.gap_id or f"RT-{g.id}", "type": g.type, "title": g.title, "finding": d.get("finding") or d.get("detail", ""),
                        "evidence": d.get("evidence", []), "surfaced_by": [g.scenario_id] if g.scenario_id else [], "proposal": d.get("proposal", ""),
                        "comparison": d.get("comparison"), "checkpoint": g.checkpoint, "case_id": g.case_id, "origin": "runtime",
                        "status": "open", "severity": d.get("severity", "medium"), "sources": d.get("sources", []), "law_cited": d.get("law_cited", [])})
    return out


def build(runtime: list[dict] | None = None) -> dict:
    seed = yaml.safe_load(open(HERE / "seed_gaps.yaml", encoding="utf-8"))["gaps"]
    anchors = json.loads((KB / "chunks" / "anchors.json").read_text(encoding="utf-8")) if (KB / "chunks" / "anchors.json").exists() else {}
    chunks = load_chunks()
    unresolved: list[str] = []
    gaps = []
    for g in [dict(x, origin=x.get("origin", "seed")) for x in seed] + [dict(x, origin="runtime") for x in (runtime or [])]:
        resolved = []
        for ref in g.get("law_cited") or []:
            cid = anchors.get(ref["anchor"]) or (ref["anchor"] if ref["anchor"] in chunks else None)
            if cid is None:
                unresolved.append(f"{g['id']}: {ref['anchor']}")
            c = chunks.get(cid) if cid else None
            resolved.append(dict(ref, chunk_id=cid, url=c["url"] if c else None, binding=c["binding"] if c else None,
                                 kind=c["kind"] if c else None))
        g["law_cited"] = resolved
        gaps.append(g)
    return {"gaps": gaps, "unresolved_anchors": unresolved}


def to_markdown(reg: dict) -> str:
    gaps = reg["gaps"]
    L = ["# VeriDiplo gap register (generated by kb/gaps/export_gaps.py — do not edit)", "",
         "| ID | Type | Severity | Title | Surfaced by | Origin |", "|---|---|---|---|---|---|"]
    for g in gaps:
        L.append(f"| {g['id']} | {g['type']} | {g.get('severity','')} | {g['title']} | {', '.join(g.get('surfaced_by') or []) or '-'} | {g.get('origin')} |")
    for g in gaps:
        L += ["", f"## {g['id']} — {g['title']}", "", f"*Type:* {g['type']} · *Severity:* {g.get('severity','-')} · *Status:* {g.get('status','open')} · *Origin:* {g.get('origin')}", "",
              "**Finding.** " + " ".join(str(g.get("finding", "")).split())]
        if g.get("correction"):
            L += ["", "**Correction vs first seed.** " + g["correction"]]
        if g.get("law_cited"):
            L += ["", "**Law / text cited (KB chunks).**"]
            for r in g["law_cited"]:
                L.append(f"- {r['article']} — `{r['chunk_id']}` ({'binding' if r.get('binding') else 'non-binding'}, {r.get('kind')}): {r['note']}")
        if g.get("evidence"):
            L += ["", "**Evidence (what surfaced it).** " + "; ".join(g["evidence"])]
        L += ["", "**Proposal.** " + str(g.get("proposal", ""))]
        if g.get("comparison"):
            L += ["", "**Comparison.** " + g["comparison"]]
        if g.get("verification"):
            L += ["", "**Verification status.** " + g["verification"]]
    if reg["unresolved_anchors"]:
        L += ["", "## Unresolved anchors", ""] + [f"- {u}" for u in reg["unresolved_anchors"]]
    return "\n".join(L) + "\n"


def export(runtime: list[dict] | None = None) -> dict:
    reg = build(runtime)
    (HERE / "gap_register.json").write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (HERE / "gap_register.md").write_text(to_markdown(reg), encoding="utf-8")
    return reg


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--runtime", help="JSON file with runtime gaps")
    ap.add_argument("--db", action="store_true", help="read runtime gaps from Postgres")
    a = ap.parse_args()
    rt: list[dict] = []
    if a.runtime:
        d = json.load(open(a.runtime, encoding="utf-8"))
        rt += d["gaps"] if isinstance(d, dict) else d
    if a.db:
        rt += runtime_from_db()
    reg = export(rt)
    print(f"gap register: {len(reg['gaps'])} gaps ({sum(1 for g in reg['gaps'] if g['origin']=='runtime')} runtime); unresolved anchors: {len(reg['unresolved_anchors'])}")
    for u in reg["unresolved_anchors"]:
        print("  UNRESOLVED", u)
    sys.exit(1 if reg["unresolved_anchors"] else 0)
