def get_lang() -> str:
    try:
        return st.session_state.get("_lang", DEFAULT_LANG)
    except Exception:
        return DEFAULT_LANG


def init_lang() -> None:
    """First run of a session: honour a deep link such as ?lang=en (also used by the screenshot script)."""
    if "_lang" not in st.session_state:
        try:
            q = st.query_params.get("lang")
        except Exception:
            q = None
        st.session_state["_lang"] = q if q in ("fr", "en") else DEFAULT_LANG


def set_lang(lang: str) -> None:
    st.session_state["_lang"] = "en" if lang == "en" else "fr"


def t(key: str, **fmt: Any) -> str:
    """Translate `key` into the current language (falls back to FR, then to the key itself)."""
    s = STRINGS.get(get_lang(), {}).get(key) or STRINGS["fr"].get(key) or key
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, IndexError):
            return s
    return s
